function openCertificateModal(resourcePath) {
  const modal = document.getElementById("certificate-modal");
  const img = document.getElementById("certificate-modal-image");
  if (!modal || !img) return;

  let iframe = document.getElementById("certificate-modal-iframe");
  if (resourcePath.toLowerCase().endsWith(".pdf")) {
    img.style.display = "none";
    if (!iframe) {
      iframe = document.createElement("iframe");
      iframe.id = "certificate-modal-iframe";
      iframe.className = "w-full h-[85vh] rounded-xl border-0 bg-slate-950";
      img.parentNode.appendChild(iframe);
    }
    iframe.style.display = "block";
    iframe.src = resourcePath;
  } else {
    if (iframe) iframe.style.display = "none";
    img.style.display = "block";
    img.src = resourcePath;
  }

  modal.classList.remove("hidden");
  document.body.style.overflow = "hidden";
}

function closeModal(modalId) {
  const modal = document.getElementById(modalId);
  if (modal) {
    modal.classList.add("hidden");
    document.body.style.overflow = "auto";
    const iframe = document.getElementById("certificate-modal-iframe");
    if (iframe) iframe.src = "";
  }
}

// Setup Event Listeners
function setupEventListeners() {
  // Project category filters
  const projectFilters = document.querySelectorAll(".project-filter-btn");
  projectFilters.forEach(btn => {
    btn.addEventListener("click", () => {
      projectFilters.forEach(b => b.classList.remove("active", "bg-blue-600", "text-white"));
      btn.classList.add("active", "bg-blue-600", "text-white");
      const category = btn.getAttribute("data-category");
      const searchInput = document.getElementById("project-search");
      renderProjects(category, searchInput ? searchInput.value : "");
    });
  });

  // Project search input
  const searchInput = document.getElementById("project-search");
  if (searchInput) {
    searchInput.addEventListener("input", (e) => {
      const activeFilter = document.querySelector(".project-filter-btn.active");
      const category = activeFilter ? activeFilter.getAttribute("data-category") : "all";
      renderProjects(category, e.target.value);
    });
  }

  // Certificate category filters
  const certFilters = document.querySelectorAll(".cert-filter-btn");
  certFilters.forEach(btn => {
    btn.addEventListener("click", () => {
      certFilters.forEach(b => b.classList.remove("active", "bg-emerald-600", "text-white"));
      btn.classList.add("active", "bg-emerald-600", "text-white");
      const category = btn.getAttribute("data-category");
      renderCertificates(category);
    });
  });

  // Close modals on escape key
  document.addEventListener("keydown", (e) => {
    if (e.key === "Escape") {
      closeModal("project-modal");
      closeModal("certificate-modal");
    }
  });

  // Modal backdrop click
  const projectModal = document.getElementById("project-modal");
  if (projectModal) {
    projectModal.addEventListener("click", (e) => {
      if (e.target === projectModal) closeModal("project-modal");
    });
  }

  const certModal = document.getElementById("certificate-modal");
  if (certModal) {
    certModal.addEventListener("click", (e) => {
      if (e.target === certModal) closeModal("certificate-modal");
    });
  }
}
